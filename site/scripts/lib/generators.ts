import { createHash } from "crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "fs";
import { dirname, join, relative, resolve } from "path";
import {
  ASSETS_DIR,
  assetPath,
  CONFIG_FILE,
  parseSiteUrl,
  validateConfig,
  type Config,
  type ResolvedConfig,
} from "@concarte/core";
import { THEME_KEYS } from "@concarte/core";
import { realAssetFile, resolveConfig } from "@concarte/core/node";
import { EventError, loadEventConfig } from "./event.ts";
import {
  areaBounds,
  mapFrame,
  PREVIEW_HEIGHT,
  PREVIEW_WIDTH,
  previewMap,
  renderPreview,
  roomFrame,
  type PreviewMap,
} from "./preview-images.ts";

export type Target = {
  /** The event to generate from. */
  eventDir: string;
  /** The site to generate into. */
  siteRoot: string;
  /** Whether to render link preview images, which only a build needs. */
  previewImages?: boolean;
};

/** A generator writes files into the site and returns what it did. */
export type Generator = (target: Target) => string | Promise<string>;

function writeGenerated(siteRoot: string, name: string, content: string) {
  const dir = join(siteRoot, "generated");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, name), content, "utf-8");
}

/**
 * Copies the assets the config references, and the favicon, to `public/`, and
 * writes `generated/assets.ts` saying whether there is a favicon. Anything
 * else in the assets folder isn't published.
 */
export const generateAssets: Generator = ({ eventDir, siteRoot }) => {
  const assetsDir = join(eventDir, ASSETS_DIR);
  const publicDir = join(siteRoot, "public");
  if (!existsSync(assetsDir)) {
    throw new EventError(`No assets directory at ${assetsDir}.`);
  }

  // Wiped first so files from a previously selected event don't leak into the build
  rmSync(publicDir, { recursive: true, force: true });
  mkdirSync(publicDir, { recursive: true });

  const config = loadEventConfig(eventDir);
  const srcs = [
    ...config.maps.flatMap((map) => [
      map.src,
      ...(map.overlays ?? []).map((overlay) => overlay.src),
    ]),
    "favicon.ico",
  ];
  for (const src of new Set(srcs.map(assetPath))) {
    const real = realAssetFile(assetsDir, src);
    if (!real) {
      if (src === "favicon.ico") {
        continue;
      }
      throw new EventError(
        `The asset ${src} is missing from ${assetsDir}, or resolves outside it.`,
      );
    }
    const target = resolve(publicDir, src);
    if (relative(publicDir, target).startsWith("..")) {
      throw new EventError(`The asset ${src} resolves outside public/.`);
    }
    mkdirSync(dirname(target), { recursive: true });
    copyFileSync(real, target);
  }

  const favicon = existsSync(join(publicDir, "favicon.ico"))
    ? "/favicon.ico"
    : null;
  writeGenerated(
    siteRoot,
    "assets.ts",
    `// AUTO-GENERATED by \`pnpm generate:assets\`. Do not edit directly.
export const favicon: string | null = ${JSON.stringify(favicon)};
`,
  );

  return `Copied ${assetsDir} to public/`;
};

function readMapSvg(eventDir: string, src: string): string {
  const assetsDir = join(eventDir, ASSETS_DIR);
  const real = realAssetFile(assetsDir, src);
  if (!real) {
    throw new Error(
      `The asset ${src} is missing from ${assetsDir}, or resolves outside it.`,
    );
  }
  return readFileSync(real, "utf-8");
}

/**
 * The event's config with every room's shape resolved to its area. Refuses a
 * config with errors.
 */
function resolveEventConfig(eventDir: string, config: Config): ResolvedConfig {
  const configPath = join(eventDir, CONFIG_FILE);

  // The editor saves configs with errors, and a watching dev server regenerates
  // on every save, so refuse here rather than overwrite the last good output.
  const errors = validateConfig(config).filter((i) => i.severity === "error");
  if (errors.length > 0) {
    throw new EventError(
      `${configPath} has errors:\n` +
        errors.map((e) => `  - ${e.message}`).join("\n"),
    );
  }

  try {
    return resolveConfig(config, (src) => readMapSvg(eventDir, src));
  } catch (error) {
    throw new EventError(
      error instanceof Error ? error.message : String(error),
    );
  }
}

/**
 * Writes `generated/config.ts`, with every room's shape resolved to its area,
 * and `generated/site.json`, the base path for `next.config.mjs`.
 */
export const generateConfig: Generator = ({ eventDir, siteRoot }) => {
  const configPath = join(eventDir, CONFIG_FILE);
  const config = loadEventConfig(eventDir);
  const resolved = resolveEventConfig(eventDir, config);

  writeGenerated(
    siteRoot,
    "config.ts",
    `// AUTO-GENERATED by \`pnpm generate:config\`. Do not edit directly.
import type { ResolvedConfig } from "@concarte/core";

const config: ResolvedConfig = ${JSON.stringify(resolved, null, 2)};

export default config;
`,
  );
  const siteUrl = parseSiteUrl(config.url);
  writeGenerated(
    siteRoot,
    "site.json",
    JSON.stringify({ basePath: siteUrl.ok ? siteUrl.basePath : "" }) + "\n",
  );
  return `Generated generated/config.ts and generated/site.json from ${configPath}`;
};

/** Writes `generated/theme.css`, the event's colours as Tailwind theme variables. */
export const generateThemeCss: Generator = ({ eventDir, siteRoot }) => {
  const config = loadEventConfig(eventDir);
  const colors = THEME_KEYS.map(
    (key) => `  --color-${key}: ${config.theme[key]};`,
  ).join("\n");
  writeGenerated(siteRoot, "theme.css", `@theme {\n${colors}\n}\n`);
  return `Generated generated/theme.css from ${join(eventDir, CONFIG_FILE)}`;
};

// sharp renders on libuv's thread pool, which has four threads by default.
// More at once only holds more copies of the map's SVG in memory.
const RENDERS_AT_ONCE = 4;

async function inParallel(jobs: (() => Promise<void>)[]): Promise<void> {
  let next = 0;
  const worker = async () => {
    while (next < jobs.length) {
      await jobs[next++]();
    }
  };
  await Promise.all(Array.from({ length: RENDERS_AT_ONCE }, worker));
}

/**
 * Renders a link preview image of each map and room into `public/og/`, and
 * writes `generated/preview-images.ts` saying where each is. Only when the
 * event turns them on and the caller asks for them: rendering is too slow to
 * repeat on every save while previewing.
 */
export const generatePreviewImages: Generator = async ({
  eventDir,
  siteRoot,
  previewImages,
}) => {
  const maps: Record<string, string> = {};
  const rooms: Record<string, Record<string, string>> = {};
  const writeList = () =>
    writeGenerated(
      siteRoot,
      "preview-images.ts",
      `// AUTO-GENERATED by \`pnpm generate --preview-images\`. Do not edit directly.
export const size = ${JSON.stringify({ width: PREVIEW_WIDTH, height: PREVIEW_HEIGHT })};

/** The link preview image of each map, by map id. */
export const maps: Record<string, string> = ${JSON.stringify(maps, null, 2)};

/** The link preview image of each room, by map id and then room id. */
export const rooms: Record<string, Record<string, string>> = ${JSON.stringify(rooms, null, 2)};
`,
    );

  const config = loadEventConfig(eventDir);
  if (!config.previewImages) {
    writeList();
    return "Skipped link preview images, which the event has turned off";
  }
  if (!previewImages) {
    writeList();
    return "Skipped link preview images, which only a build makes";
  }

  const outDir = join(siteRoot, "public", "og");
  mkdirSync(outDir, { recursive: true });
  // Named by content so that sites which cache previews by address fetch a
  // changed image, and so that ids needn't be safe as file names.
  const save = (png: Buffer): string => {
    const name = `${createHash("sha256").update(png).digest("hex").slice(0, 16)}.png`;
    writeFileSync(join(outDir, name), png);
    return `/og/${name}`;
  };

  const failure = (what: string, error: unknown) =>
    new EventError(
      `Couldn't make the link preview image of ${what}: ${error instanceof Error ? error.message : String(error)}`,
    );
  type Job = {
    what: string;
    render: () => Promise<Buffer>;
    done: (file: string) => void;
  };
  const jobs: Job[] = [];
  for (const map of resolveEventConfig(eventDir, config).maps) {
    const where = `map "${map.id}" (${map.src})`;
    let preview: PreviewMap;
    try {
      preview = previewMap(readMapSvg(eventDir, map.src));
    } catch (error) {
      throw failure(where, error);
    }
    jobs.push({
      what: where,
      render: async () =>
        renderPreview(preview, mapFrame(preview.box), config.theme),
      done: (file) => {
        maps[map.id] = file;
      },
    });
    const mapRooms: Record<string, string> = {};
    rooms[map.id] = mapRooms;
    for (const room of map.rooms) {
      jobs.push({
        what: `room "${room.id}" on ${where}`,
        render: async () =>
          renderPreview(
            preview,
            roomFrame(areaBounds(room.area), preview.box),
            config.theme,
            room.area,
          ),
        done: (file) => {
          mapRooms[room.id] = file;
        },
      });
    }
  }
  await inParallel(
    jobs.map(({ what, render, done }) => async () => {
      try {
        done(save(await render()));
      } catch (error) {
        throw failure(what, error);
      }
    }),
  );
  writeList();
  return `Rendered ${jobs.length} link preview images into public/og/`;
};

export const generators: Generator[] = [
  generateAssets,
  generateConfig,
  generateThemeCss,
  generatePreviewImages,
];
