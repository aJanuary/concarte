import { format, resolveConfig } from "prettier";
import {
  configOrder,
  keysOf,
  linkOrder,
  mapOrder,
  overlayOrder,
  roomOrder,
  roomRef,
  themeOrder,
  type Config,
  type MapConfig,
  type Overlay,
  type Room,
} from "../shared/schema.ts";
import { tidyText } from "../shared/text.ts";

const HEADER = `// Generated by the ConCarte editor. Comments are not preserved when the
// editor saves, so keep notes elsewhere.
`;

function tidyList(list: string[] | undefined): string[] | undefined {
  return list && list.length > 0 ? list : undefined;
}

function tidyRoom(room: Room): Room {
  const ref = roomRef(room);
  if (ref === undefined) {
    throw new Error(`Room "${room.id}" does not have a { ref } area`);
  }
  const description = room.description ? tidyText(room.description) : "";
  return {
    id: room.id,
    label: room.label,
    aliases: tidyList(room.aliases),
    description: description === "" ? undefined : description,
    link: room.link
      ? { href: room.link.href, title: room.link.title }
      : undefined,
    searchable: room.searchable,
    area: { ref },
  };
}

function tidyMap(map: MapConfig): MapConfig {
  return {
    id: map.id,
    label: map.label,
    src: map.src,
    overlays:
      map.overlays && map.overlays.length > 0
        ? map.overlays.map((o) => ({ id: o.id, label: o.label, src: o.src }))
        : undefined,
    rooms: map.rooms.map(tidyRoom),
  };
}

export function normalizeConfig(config: Config): Config {
  return {
    eventName: config.eventName,
    locale: config.locale,
    description: tidyText(config.description),
    attributions: tidyList(config.attributions?.filter((a) => a.trim() !== "")),
    theme: { ...config.theme },
    filters: tidyList(config.filters),
    defaultMap: config.defaultMap || undefined,
    maps: config.maps.map(tidyMap),
  };
}

const pad = (depth: number) => "  ".repeat(depth);

function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function escapeTemplate(text: string): string {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

function emitString(value: string, depth: number, multiline: boolean): string {
  if (multiline && value.includes("\n")) {
    const lines = value
      .split("\n")
      .map((line) => (line.trim() === "" ? "" : pad(depth + 1) + line));
    return "`\n" + escapeTemplate(lines.join("\n")) + "\n" + pad(depth) + "`";
  }
  return JSON.stringify(value);
}

function emitStrings(
  values: string[],
  depth: number,
  multiline: boolean,
): string {
  const items = values.map(
    (v) => pad(depth + 1) + emitString(v, depth + 1, multiline) + ",",
  );
  return "[\n" + items.join("\n") + "\n" + pad(depth) + "]";
}

function emitObject(entries: [string, string][], depth: number): string {
  const lines = entries.map(([k, v]) => `${pad(depth + 1)}${key(k)}: ${v},`);
  return "{\n" + lines.join("\n") + "\n" + pad(depth) + "}";
}

function emitList(items: string[], depth: number): string {
  const lines = items.map((item) => pad(depth + 1) + item + ",");
  return "[\n" + lines.join("\n") + "\n" + pad(depth) + "]";
}

/** Multi-line markdown is dedented on load, so it can be indented to fit. */
const MARKDOWN = true;

function emitOverlay(overlay: Overlay, depth: number): string {
  return emitObject(
    keysOf<Overlay>(overlayOrder).map((k) => [
      k,
      emitString(overlay[k], depth + 1, false),
    ]),
    depth,
  );
}

function emitRoom(room: Room, depth: number): string {
  const entries: [string, string][] = [];
  for (const k of keysOf<Room>(roomOrder)) {
    switch (k) {
      case "id":
      case "label":
        entries.push([k, emitString(room[k], depth + 1, false)]);
        break;
      case "aliases":
        if (room.aliases) {
          entries.push([k, emitStrings(room.aliases, depth + 1, false)]);
        }
        break;
      case "description":
        if (room.description !== undefined) {
          entries.push([k, emitString(room.description, depth + 1, MARKDOWN)]);
        }
        break;
      case "link":
        if (room.link) {
          entries.push([
            k,
            emitObject(
              keysOf<NonNullable<Room["link"]>>(linkOrder).map((lk) => [
                lk,
                emitString(room.link![lk], depth + 2, false),
              ]),
              depth + 1,
            ),
          ]);
        }
        break;
      case "searchable":
        if (room.searchable !== undefined) {
          entries.push([k, room.searchable === true ? "true" : "false"]);
        }
        break;
      case "area":
        entries.push([k, `{ ref: ${JSON.stringify(roomRef(room))} }`]);
        break;
      default:
        assertNever(k);
    }
  }
  return emitObject(entries, depth);
}

function emitMap(map: MapConfig, depth: number): string {
  const entries: [string, string][] = [];
  for (const k of keysOf<MapConfig>(mapOrder)) {
    switch (k) {
      case "id":
      case "label":
      case "src":
        entries.push([k, emitString(map[k], depth + 1, false)]);
        break;
      case "overlays":
        if (map.overlays) {
          entries.push([
            k,
            emitList(
              map.overlays.map((o) => emitOverlay(o, depth + 2)),
              depth + 1,
            ),
          ]);
        }
        break;
      case "rooms":
        entries.push([
          k,
          map.rooms.length === 0
            ? "[]"
            : emitList(
                map.rooms.map((r) => emitRoom(r, depth + 2)),
                depth + 1,
              ),
        ]);
        break;
      default:
        assertNever(k);
    }
  }
  return emitObject(entries, depth);
}

function assertNever(value: never): never {
  throw new Error(`Unhandled field: ${String(value)}`);
}

function emitConfig(config: Config): string {
  const entries: [string, string][] = [];
  for (const k of keysOf<Config>(configOrder)) {
    switch (k) {
      case "eventName":
      case "locale":
        entries.push([k, emitString(config[k], 1, false)]);
        break;
      case "description":
        entries.push([k, emitString(config.description, 1, MARKDOWN)]);
        break;
      case "attributions":
        if (config.attributions) {
          entries.push([k, emitStrings(config.attributions, 1, false)]);
        }
        break;
      case "theme":
        entries.push([
          k,
          emitObject(
            keysOf<Config["theme"]>(themeOrder).map((tk) => [
              tk,
              emitString(config.theme[tk], 2, false),
            ]),
            1,
          ),
        ]);
        break;
      case "filters":
        if (config.filters) {
          entries.push([k, emitStrings(config.filters, 1, false)]);
        }
        break;
      case "defaultMap":
        if (config.defaultMap !== undefined) {
          entries.push([k, emitString(config.defaultMap, 1, false)]);
        }
        break;
      case "maps":
        entries.push([
          k,
          emitList(
            config.maps.map((m) => emitMap(m, 2)),
            1,
          ),
        ]);
        break;
      default:
        assertNever(k);
    }
  }
  return emitObject(entries, 0);
}

/**
 * Produces the source of an event's config.ts. `filepath` selects the prettier
 * configuration to format with.
 */
export async function serializeConfig(
  config: Config,
  filepath: string,
): Promise<string> {
  const source =
    HEADER +
    `import { Config } from "../../app/config.types";\n\n` +
    `const config: Config = ${emitConfig(normalizeConfig(config))};\n\n` +
    `export default config;\n`;
  const options = (await resolveConfig(filepath)) ?? {};
  return format(source, { ...options, filepath });
}
