#!/usr/bin/env tsx
import { writeFileSync, mkdirSync, readFileSync } from "fs";
import { join } from "path";
import { assetsDir, eventLabel, loadEventConfig } from "./lib/event.js";
import { resolveConfig } from "./lib/resolve-config.js";
import { validateConfig } from "./lib/validate-config.js";
import { green } from "./lib/console-color.js";

async function main() {
  const config = await loadEventConfig();

  // The editor saves configs with errors, and a watching dev server regenerates
  // on every save, so refuse here rather than overwrite the last good output.
  const errors = validateConfig(config).filter((i) => i.severity === "error");
  if (errors.length > 0) {
    console.error(
      `${eventLabel}/concarte.json has errors:\n` +
        errors.map((e) => `  - ${e.message}`).join("\n"),
    );
    process.exit(1);
  }

  let resolved;
  try {
    resolved = resolveConfig(config, (src) =>
      readFileSync(join(assetsDir, src), "utf-8"),
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }

  const outputDir = join(process.cwd(), "generated");
  mkdirSync(outputDir, { recursive: true });
  const outputPath = join(outputDir, "config.ts");
  writeFileSync(
    outputPath,
    `// AUTO-GENERATED by \`pnpm generate:config\` from ${eventLabel}/concarte.json. Do not edit directly.
  import { Config } from "../app/config.types";

  const config: Config = ${JSON.stringify(resolved, null, 2)};

  export default config;
  `,
    "utf-8",
  );

  console.log(
    ` ${green("✓")} Generated generated/config.ts from ${eventLabel}/concarte.json`,
  );
}

main();
